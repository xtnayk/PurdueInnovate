const checks=[];
const check=(value,label)=>{if(!value)throw new Error(label);checks.push(label);};
const waitFor=async(predicate)=>{for(let i=0;i<240;i++){if(predicate())return;await new Promise(r=>setTimeout(r,50));}throw new Error('Timed out waiting for UI');};
await waitFor(()=>state.result&&!state.busy);
check(document.querySelectorAll('[role="tab"][data-fleet-tab]').length===5,'All fleet and four rig tabs appear');
check(!state.fleetStore.snapshot().active,'Fresh job log has no approved plan');
check(state.fleetStore.completedIds().length===0,'A planned schedule is not counted as done');
document.querySelector('[data-fleet-action="approve"]').click();
check(document.querySelector('#approval-dialog').open,'Fleet approval opens the review dialog');
document.querySelector('#confirm-approval').click();
await waitFor(()=>!!state.fleetStore.snapshot().active&&!document.querySelector('#approval-dialog').open);
const active=state.fleetStore.snapshot().active;
check(active.plan.schedule.length>0,'Approval populates the active workboard');
const jobs=active.plan.schedule.filter(j=>j.rig_id==='R1').sort((a,b)=>a.start-b.start);
window.__fleetQaFirst=jobs[0].field_id;
document.querySelector('[data-fleet-tab="R1"]').click();
check([...document.querySelectorAll('[data-fleet-job-row]')].map(n=>n.dataset.fleetJobRow).join(',')===jobs.map(j=>j.field_id).join(','),'Rig tab displays its jobs in solver order');
check(document.querySelector(`[data-fleet-field="${jobs[1].field_id}"][data-fleet-status="in_progress"]`).disabled,'Later jobs cannot start before the first queued field');
document.querySelector(`[data-fleet-field="${jobs[0].field_id}"][data-fleet-status="in_progress"]`).click();
check(state.fleetStore.snapshot().records[jobs[0].field_id].status==='in_progress','Start job records the job in progress');
check(document.querySelector(`[data-fleet-field="${jobs[1].field_id}"][data-fleet-status="in_progress"]`).disabled,'A rig cannot start a second simultaneous job');
document.querySelector('[data-fleet-tab="R2"]').click();
const second=active.plan.schedule.filter(j=>j.rig_id==='R2').sort((a,b)=>a.start-b.start)[0];
document.querySelector(`[data-fleet-field="${second.field_id}"][data-fleet-status="in_progress"]`).click();
check(Object.values(state.fleetStore.snapshot().records).filter(j=>j.status==='in_progress').length===2,'Separate sprayers can work concurrently');
document.querySelector(`[data-fleet-field="${second.field_id}"][data-fleet-status="held"]`).click();
check(state.fleetStore.snapshot().records[second.field_id].status==='held','Hold retains a visible job');
document.querySelector(`[data-fleet-field="${second.field_id}"][data-fleet-status="queued"]`).click();
check(state.fleetStore.snapshot().records[second.field_id].status==='queued','Resume returns a held job to the queue');
document.querySelector('[data-fleet-tab="R1"]').click();
document.querySelector(`[data-fleet-field="${jobs[0].field_id}"][data-fleet-status="done"]`).click();
check(state.fleetStore.completedIds().length===1,'Mark done increments completed fields once');
check(document.querySelector('[role="progressbar"]').getAttribute('aria-valuenow')==='1','Fleet progress reflects manual completion');
check(document.querySelector('.fleet-history').textContent.includes(state.meta.fields.find(f=>f.id===jobs[0].field_id).name),'Completed job appears in history');
check(!document.querySelector(`[data-fleet-field="${jobs[1].field_id}"][data-fleet-status="in_progress"]`).disabled,'The next field becomes startable');
document.querySelector('[data-view="board"]').click();
const scrub=document.querySelector('#simulation-scrub');scrub.value='1080';scrub.dispatchEvent(new Event('input',{bubbles:true}));
check(state.fleetStore.completedIds().length===1,'3D playback does not mark real jobs done');
check(document.querySelector('#board-completed').textContent==='1','Planning board shares completion count');
const oldRun=state.result.run_id;
document.querySelector('#replan-button').click();
await waitFor(()=>!state.busy&&state.result.run_id!==oldRun);
check(state.result.completed_fields.includes(jobs[0].field_id),'Local replan receives the completed field');
check(state.result.plans.every(p=>!p.schedule.some(j=>j.field_id===jobs[0].field_id)&&!p.deferred.some(j=>j.field_id===jobs[0].field_id)),'Completed field is absent from new jobs and deferrals');
check(state.fleetStore.snapshot().active.run_id===active.run_id,'A draft replan does not replace active queues');
document.querySelector('[data-view="fleet"]').click();
document.querySelector('[data-fleet-action="approve"]').click();
document.querySelector('#confirm-approval').click();
await waitFor(()=>state.fleetStore.snapshot().active.run_id===state.result.run_id);
check(state.fleetStore.completedIds().length===1,'Approving a replacement retains completion history');
check(!state.fleetStore.snapshot().active.plan.schedule.some(j=>j.field_id===jobs[0].field_id),'Replacement queue does not repeat completed work');
window.__fleetQaChecks=checks;
return {passed:checks.length,checks,completedField:jobs[0].field_id};
