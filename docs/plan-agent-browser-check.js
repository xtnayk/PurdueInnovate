const check=(v,label)=>{if(!v)throw new Error(label);checks.push(label);};
const waitFor=async(fn)=>{for(let i=0;i<300;i++){if(fn())return;await new Promise(r=>setTimeout(r,50));}throw new Error('UI timeout');};
const click=sel=>{const el=document.querySelector(sel);if(!el||el.disabled)throw new Error('Unavailable '+sel);el.click();};
const fill=(sel,text)=>{const el=document.querySelector(sel);el.value=text;el.dispatchEvent(new Event('input',{bubbles:true}));};
await waitFor(()=>state.result&&!state.busy);
check(state.view==='board','Plan opens directly from its URL');
check(document.querySelector('#plan-agent-content').innerText.includes('Planning agent'),'Plan dashboard contains the planning agent');
check(document.querySelectorAll('#feedback-draft').length===1,'Only one feedback composer exists');
check(document.querySelector('#plan-feedback-slot').contains(document.querySelector('#proposal-feedback-content')),'The shared feedback panel is on Plan');
check(!document.querySelector('#plan-feedback-details').open,'The conversation starts compact');
click('[data-plan-agent-action="feedback"]');
check(document.querySelector('#plan-feedback-details').open&&document.activeElement.matches('[data-feedback-draft]'),'Request changes expands and focuses Plan feedback');
fill('[data-feedback-draft]','Lower cost');
click('[data-view="disruptions"]');
check(document.querySelector('#disruption-feedback-slot').contains(document.querySelector('#proposal-feedback-content')),'Disruptions receives the same conversation panel');
check(document.querySelector('[data-feedback-draft]').value==='Lower cost','Unsubmitted draft survives switching to Disruptions');
click('[data-view="board"]');click('[data-feedback-action="review"]');
check(state.feedback.review?.supported,'Feedback can be reviewed on Plan');
check(document.querySelector('#plan-feedback-slot').contains(document.querySelector('.feedback-interpretation')),'Interpretation stays on Plan');
const original=JSON.stringify(state.fleetStore.snapshot().active);
click('[data-feedback-action="apply"]');await waitFor(()=>!state.busy&&state.disruptionPhase==='ready');
check(state.view==='board','Feedback replanning keeps the farmer on Plan');
check(state.priority==='cost'&&state.result.plans[0].estimated_cost<=state.result.plans.at(-1).estimated_cost,'Plan feedback applies the requested ranking');
check(JSON.stringify(state.fleetStore.snapshot().active)===original,'Feedback never activates a fleet plan');
click('[data-plan-agent-action="approve"]');
check(document.querySelector('#approval-dialog').open,'Plan agent uses the human approval dialog');
check(document.querySelectorAll('.approval-action-list p').length===state.meta.rigs.length,'Approval includes every sprayer');
