check(document.querySelector('#plan-agent-content').innerText.includes('Approved'),'Plan agent reflects approved status');
click('[data-scenario="breakdown"]');
check(document.querySelector('[data-plan-agent-action="approve"]').disabled,'Changed conditions disable stale Plan approval');
click('[data-plan-agent-action="replan"]');await waitFor(()=>!state.busy&&state.disruptionPhase==='ready');
check(state.view==='board'&&!document.querySelector('[data-plan-agent-action="approve"]').disabled,'Agent replans in place and enables review of the new response');
click('[data-view="disruptions"]');
check(state.feedback.history.some(h=>h.role==='user'&&h.text==='Lower cost'),'Plan feedback history is also available in Disruptions');
click('[data-view="board"]');
const ids=[...document.querySelectorAll('[id]')].map(e=>e.id);
check(new Set(ids).size===ids.length,'Switching tabs introduces no duplicate DOM IDs');
return {passed:checks.length,checks,offline:!!window.FIELDWORK_REPLAY};
